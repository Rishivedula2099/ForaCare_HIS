"use client";

import React, { useEffect, useMemo, useRef, useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { Download, ExternalLink, Printer } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Select } from "@/components/ui/select";
import { ErrorState } from "@/components/states/error-state";
import { Spinner } from "@/components/states/loading-state";
import {
  DocumentFetchError,
  DocumentType,
  fetchDocumentPdf,
  listDocumentTypes,
} from "@/lib/documents-api";
import { cn } from "@/lib/utils";
import {
  CUSTOM_PAPER_MAX_MM,
  CUSTOM_PAPER_MIN_MM,
  PAPER_SIZE_LABELS,
  PaperSize,
} from "@/types/documents";
import { Input } from "@/components/ui/input";

interface DocumentPreviewProps {
  type: DocumentType;
  resourceId: string;
  /** Download file name (without extension). Defaults to the document type. */
  fileName?: string;
  /** Reproduce the document with this template version instead of the active one. */
  templateVersion?: number;
  className?: string;
}

const TEMPLATE_DEFAULT = "DEFAULT";

const PAPER_OPTIONS = [
  { value: TEMPLATE_DEFAULT, label: "Template default" },
  ...(Object.keys(PAPER_SIZE_LABELS) as PaperSize[]).map((value) => ({
    value,
    label: PAPER_SIZE_LABELS[value],
  })),
];

/**
 * Reusable print controls + preview for any document generated by the
 * backend document engine: in-page preview (iframe) with loading and error
 * states, paper-size selection, Print, open-preview-in-tab and PDF download.
 */
export function DocumentPreview({
  type,
  resourceId,
  fileName,
  templateVersion,
  className,
}: DocumentPreviewProps) {
  const frameRef = useRef<HTMLIFrameElement>(null);
  const [paperChoice, setPaperChoice] = useState<string>(TEMPLATE_DEFAULT);
  const [customWidth, setCustomWidth] = useState("50");
  const [customHeight, setCustomHeight] = useState("25");

  // Whether this document type honours a paper size (e.g. the lab report is fixed A4).
  const typesQuery = useQuery({ queryKey: ["document-types"], queryFn: listDocumentTypes });
  const supportsPaperSize =
    typesQuery.data?.find((info) => info.code === type)?.supports_templates ?? false;
  const paperSize =
    supportsPaperSize && paperChoice !== TEMPLATE_DEFAULT ? (paperChoice as PaperSize) : undefined;

  // Custom sizes are only sent once both dimensions are valid.
  const widthMm = Number(customWidth);
  const heightMm = Number(customHeight);
  const inRange = (n: number) => n >= CUSTOM_PAPER_MIN_MM && n <= CUSTOM_PAPER_MAX_MM;
  const customValid = inRange(widthMm) && inRange(heightMm);
  const isCustom = paperSize === "CUSTOM";

  const query = useQuery({
    queryKey: [
      "document", type, resourceId, paperSize ?? null, templateVersion ?? null,
      isCustom ? `${widthMm}x${heightMm}` : null,
    ],
    queryFn: () => fetchDocumentPdf(type, resourceId, { paperSize, templateVersion, widthMm, heightMm }),
    enabled: !!resourceId && (!isCustom || customValid),
    retry: false,
    // A generated document is a snapshot; refetch only on explicit retry.
    staleTime: 5 * 60 * 1000,
  });

  const blob = query.data;
  const objectUrl = useMemo(() => (blob ? URL.createObjectURL(blob) : null), [blob]);
  useEffect(() => {
    if (!objectUrl) return;
    return () => URL.revokeObjectURL(objectUrl);
  }, [objectUrl]);

  const handlePrint = () => {
    const frame = frameRef.current?.contentWindow;
    if (!frame) return;
    frame.focus();
    frame.print();
  };

  const handleOpenPreview = () => {
    if (objectUrl) window.open(objectUrl, "_blank", "noopener");
  };

  const handleDownload = () => {
    if (!objectUrl) return;
    const link = document.createElement("a");
    link.href = objectUrl;
    link.download = `${fileName ?? type.toLowerCase()}.pdf`;
    link.click();
  };

  const ready = !!objectUrl && !query.isFetching && (!isCustom || customValid);
  const error = query.error as DocumentFetchError | null;

  return (
    <div className={cn("flex flex-col gap-3", className)}>
      <div className="flex flex-wrap items-center justify-end gap-2 print:hidden">
        {supportsPaperSize && (
          <div className="flex items-center gap-2 mr-auto">
            <span className="text-[11px] font-semibold text-slate-700">Paper size</span>
            <Select
              options={PAPER_OPTIONS}
              value={paperChoice}
              onChange={setPaperChoice}
              className="w-44"
            />
            {isCustom && (
              <>
                <Input
                  type="number"
                  aria-label="Width in mm"
                  value={customWidth}
                  onChange={(e) => setCustomWidth(e.target.value)}
                  className="w-20 text-xs"
                />
                <span className="text-xs text-slate-500">×</span>
                <Input
                  type="number"
                  aria-label="Height in mm"
                  value={customHeight}
                  onChange={(e) => setCustomHeight(e.target.value)}
                  className="w-20 text-xs"
                />
                <span className="text-[11px] text-slate-500">mm</span>
              </>
            )}
          </div>
        )}
        <Button size="sm" variant="outline" onClick={handleOpenPreview} disabled={!ready} className="gap-1.5">
          <ExternalLink className="w-3.5 h-3.5" />
          Preview
        </Button>
        <Button size="sm" variant="outline" onClick={handleDownload} disabled={!ready} className="gap-1.5">
          <Download className="w-3.5 h-3.5" />
          PDF
        </Button>
        <Button size="sm" onClick={handlePrint} disabled={!ready} className="gap-1.5">
          <Printer className="w-3.5 h-3.5" />
          Print
        </Button>
      </div>

      <div className="rounded-md border border-slate-200 bg-slate-50 min-h-[70vh] overflow-hidden">
        {isCustom && !customValid && (
          <p className="text-xs text-amber-700 p-6 text-center">
            Enter a width and height between {CUSTOM_PAPER_MIN_MM} and {CUSTOM_PAPER_MAX_MM} mm.
          </p>
        )}
        {query.isFetching && <Spinner label="Preparing document..." className="py-32" />}
        {query.isError && !query.isFetching && (
          <ErrorState
            title="Unable to load document"
            description={error?.message}
            correlationId={error?.requestId}
            onRetry={() => query.refetch()}
          />
        )}
        {ready && (
          <iframe
            ref={frameRef}
            src={objectUrl}
            title="Document preview"
            className="w-full h-[80vh] bg-white"
          />
        )}
      </div>
    </div>
  );
}
